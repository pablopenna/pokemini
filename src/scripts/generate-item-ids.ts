import * as fs from 'fs';
import * as path from 'path';

import type { ItemData } from '#/types/item-data.ts';

const ITEMS_DIR = path.join('src', 'data', 'items');
const OUTPUT_FILE = path.join('src', 'types', 'item-id.ts');

/** "Poké Ball" -> "PokeBall", "DNA Splicers" -> "DNASplicers". */
const toPascalCase = (value: string) => value
  .normalize('NFD').replace(/[\u0300-\u036f]/g, '')
  .replace(/['’]/g, '')
  .split(/[^A-Za-z0-9]+/)
  .filter(Boolean)
  .map(word => word[0].toUpperCase() + word.slice(1))
  .join('');

const items: ItemData[] = fs.readdirSync(ITEMS_DIR)
  .filter(file => file.endsWith('.json'))
  .map(file => JSON.parse(fs.readFileSync(path.join(ITEMS_DIR, file), 'utf8')) as ItemData);

/** "Poké Ball" -> "pokeball", used to find an item's base slug despite punctuation differences (e.g. "S.S. Ticket" -> `ss-ticket`). */
const compact = (value: string) => value
  .normalize('NFD').replace(/[\u0300-\u036f]/g, '')
  .toLowerCase()
  .replace(/[^a-z0-9]/g, '');

const isBaseItem = (item: ItemData) => compact(item.id) === compact(item.name);

/** "Poké Ball" -> "poke-ball", used to find an item's base slug from its displayed name. */
const toSlug = (name: string) => name
  .normalize('NFD').replace(/[\u0300-\u036f]/g, '')
  .toLowerCase()
  .replace(/['’]/g, '')
  .replace(/[^a-z0-9]+/g, '-')
  .replace(/^-|-$/g, '');

const nameKey = (item: ItemData) => /^[A-Za-z]/.test(item.name) ? toPascalCase(item.name) : '';

/** Slug-based fallback for items whose names are duplicated or not usable as identifiers (e.g. "★And15"). */
const slugKey = (item: ItemData) => toPascalCase(item.id.replace(/--/g, '-'));

/**
 * Distinguishing part of an item's slug, e.g. "bag" for `aloraichium-z--bag` or
 * "goldenrod" for `basement-key--goldenrod`. Empty for the base item.
 */
const variant = (item: ItemData): { prefix?: string; suffix?: string } => {
  if (isBaseItem(item)) return {};

  const [base, ...rest] = item.id.split('--');
  if (rest.length) return { suffix: toPascalCase(rest.join('-')) };

  const baseSlug = toSlug(item.name);
  // Legends: Arceus variants are prefixed with "la" (e.g. `lagreat-ball`).
  if (item.id.startsWith('la') && compact(item.id.slice(2)) === compact(item.name)) return { prefix: 'La' };

  // Extra slug tokens, e.g. the "f" in `nidoran-f-candy`.
  const baseTokens = new Set(baseSlug.split('-'));
  const extra = base.split('-').filter(token => !baseTokens.has(token));
  return extra.length ? { suffix: toPascalCase(extra.join('-')) } : {};
};

const byNameKey = new Map<string, ItemData[]>();
for (const item of items) {
  const key = nameKey(item) || slugKey(item);
  byNameKey.set(key, [...(byNameKey.get(key) ?? []), item]);
}

const ids = new Map<string, ItemData>();
for (const [key, group] of byNameKey) {
  if (group.length === 1) {
    ids.set(key, group[0]);
    continue;
  }

  // Duplicate names (e.g. "Poké Ball" and the Legends: Arceus variant) are distinguished by their slug.
  const base = group.find(isBaseItem);
  const ordered = base ? [base, ...group.filter(item => item !== base)] : group;
  for (const item of ordered) {
    const { prefix = '', suffix = '' } = variant(item);
    const isBase = !prefix && !suffix;
    let memberKey = prefix ? `${prefix}${key}` : `${key}${suffix}`;
    if (isBase ? ids.has(memberKey) : memberKey === key || ids.has(memberKey)) {
      memberKey = slugKey(item);
    }
    ids.set(memberKey, item);
  }
}

const seen = new Map<string, string>();
for (const [key, item] of ids) {
  if (!/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key)) {
    throw new Error(`Invalid enum key "${key}" for item "${item.id}"`);
  }
  const duplicate = seen.get(key);
  if (duplicate) throw new Error(`Duplicate enum key "${key}" for "${duplicate}" and "${item.id}"`);
  seen.set(key, item.id);
}

const members = [...ids]
  .sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0)
  .map(([key, item]) => `  ${key} = '${item.id}',`)
  .join('\n');

const output = `// Generated by \`npm run generateitemids\`. Do not edit by hand.

export enum ItemId {
${members}
}
`;

fs.writeFileSync(OUTPUT_FILE, output);
console.log(`Wrote ${ids.size} item ids to ${OUTPUT_FILE}`);
